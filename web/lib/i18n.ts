const BN_DIGITS = "০১২৩৪৫৬৭৮৯";
export const toLangDigits = (value: string | number, lang: Lang) =>
  lang === "bn" ? String(value).replace(/\d/g, (d) => BN_DIGITS[Number(d)]) : String(value);

